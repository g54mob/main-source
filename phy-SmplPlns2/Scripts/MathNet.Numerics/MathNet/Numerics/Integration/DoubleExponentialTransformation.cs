			}
			double num = ((level <= 1) ? 1.0 : (1.0 / (double)(2 << level - 2)));
			double num2 = ((level == 0) ? 0.0 : (1.0 / (double)(2 << level - 1)));
			int num3 = ((level == 0) ? 4 : (3 << level - 1));
			double num4 = 0.0;
			double[] array = new double[num3];
			for (int i = 0; i < array.Length; i++)
