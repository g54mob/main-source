		}

		private static Vector3 LimitVector(Vector3 v, bool allowNegative = true)
		{
			v.x = (float)GetDoubleValue(v.x, allowNegative);
			v.y = (float)GetDoubleValue(v.y, allowNegative);
			v.z = (float)GetDoubleValue(v.z, allowNegative);
			return v;
		}

		private static Vector3d Vec(Vector3d? v)
		{
			if (!v.HasValue)
			{
				return Vector3d.zero;
			}
			return v.Value;
		}

		private static Vector3d Vector2ToVector3d(Vector2? v)
		{
			if (v.HasValue)
			{
				return new Vector3d(v.Value.x, v.Value.y, 0f);
			}
			return Vector3d.zero;
		}
