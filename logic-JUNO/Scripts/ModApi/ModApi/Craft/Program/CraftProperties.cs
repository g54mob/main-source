		}

		private static double GetDoubleValue(double x, bool allowNegative = true)
		{
			if (double.IsNaN(x) || double.IsInfinity(x))
			{
				return 0.0;
			}
			if (!allowNegative && x < 0.0)
			{
				return 0.0;
			}
			return x;
		}

		private static double GetFrequencyOfNote(string note, int octave, IThreadContext c)
		{
			int num = Array.IndexOf(new string[12]
			{
				"C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A",
				"A#", "B"
			}, note) + 1;
			if (num >= 0)
			{
				return 440f * Mathf.Pow(2f, ((float)num - 10f) / 12f + ((float)octave - 4f));
			}
			c.Log.LogError("Unknown note: " + note);
			return 0.0;
		}

