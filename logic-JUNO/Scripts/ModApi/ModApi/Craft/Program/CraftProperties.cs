		public static CraftProperty AddProperty(string category, string name, string xmlName, ListItemInfoType itemType, string tooltip)
		{
			if (GetProperty(xmlName) != null)
			{
				throw new ArgumentException($"The craft property with XML name {xmlName} already exists");
			}
			CraftProperty craftProperty = new CraftProperty
			{
				Category = category,
				DisplayName = name,
				XmlName = xmlName,
				Tooltip = tooltip,
				ItemType = itemType
			};
			_properties.Add(craftProperty);
			return craftProperty;
		}

		public static List<CraftProperty> GetPropertiesInCategory(string category)
		{
			return _properties.Where((CraftProperty x) => x.Category == category).ToList();
		}

		public static CraftProperty GetProperty(string xmlName)
		{
			return _properties.Where((CraftProperty x) => x.XmlName == xmlName).FirstOrDefault();
		}

