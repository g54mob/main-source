	[PlanetModifierInfo("Texture Data (Cubemap Face)", "A planet modifier used to read data from a texture mapped to a cubemap face of the celestial body and store an output value based on that data. Rotation is limited to 90 degree increments. Textures should wrap to other faces but will not properly wrap around corners where three faces meet. Expect some distortion as the faces of the cubemap are mapped to the sphere representing the celestial body.")]
	public class TextureData : VertexDataCommonPassPlanetModifier
	{
		private enum CubeFace
		{
			Xpos = 0,
			Xneg = 1,
			Ypos = 2,
			Yneg = 3,
			Zpos = 4,
			Zneg = 5
		}

		private enum CubeFaceTextureRotation
		{
			RotateDefault = 0,
			Rotate90 = 1,
			Rotate180 = 2,
			Rotate270 = 3
		}

		[StructLayout(LayoutKind.Sequential, Size = 1)]
		private struct CubeFaceComparer : IEqualityComparer<CubeFace>
		{
			public bool Equals(CubeFace x, CubeFace y)
			{
				return x == y;
			}

			public int GetHashCode(CubeFace obj)
			{
				return (int)obj;
			}
		}

		private class CubeFaceTexture
		{
			public Vector4d Bounds;

			public CubeFace Face;

			public TextureDataSampleMode InterpolationMethod;

			public float MaxOutputValue = 1f;

			public CubeFaceTextureRotation Rotation;

			public ISingleChannelTextureDataSampler Sampler;

			public Vector2d Size;

			public float Sample(Vector2d cubePosition, float[][] tempArray)
			{
				if (cubePosition.x >= Bounds.x && cubePosition.x <= Bounds.z && cubePosition.y >= Bounds.y && cubePosition.y <= Bounds.w)
				{
					float num = (float)((cubePosition.x - Bounds.x) / Size.x);
					float num2 = (float)((cubePosition.y - Bounds.y) / Size.y);
					if (Rotation != CubeFaceTextureRotation.RotateDefault)
					{
						switch (Rotation)
						{
						case CubeFaceTextureRotation.Rotate90:
						{
							float num4 = num;
							num = 1f - num2;
							num2 = num4;
							break;
						}
						case CubeFaceTextureRotation.Rotate180:
							num = 1f - num;
							num2 = 1f - num2;
							break;
						case CubeFaceTextureRotation.Rotate270:
						{
							float num3 = num2;
							num2 = 1f - num;
							num = num3;
							break;
						}
						}
					}
					if (InterpolationMethod == TextureDataSampleMode.Bicubic)
					{
						return Sampler.SampleBicubic(num, num2, tempArray) * MaxOutputValue;
					}
					return Sampler.SampleBilinear(num, num2) * MaxOutputValue;
				}
				return 0f;
			}
		}

		[Serializable]
		private class TextureDataItem
		{
			[InspectorProperty(null, false, Label = "Cubemap Face", Order = 1, Tooltip = "The cube face of the texture's center position.")]
			public CubeFace Face;

			[InspectorProperty(null, false, Label = "Interpolation Method", Order = 6, Tooltip = "The interpolation method used when sampling the texture data. Bilinear should be much faster. Bicubic should be smoother, but may not always look better than bilinear as the look can be highly dependent on the texture content and resolution as well as the size of the texture on the celestial body. It is recommended to stick with bilinear for performance reasons unless bicubic offers a far better visual result.")]
			public TextureDataSampleMode InterpolationMethod;

			[InspectorProperty(null, false, Label = "Max Output Value", Order = 5, Tooltip = "The maximum value generated by this texture and added to the modifier output value for a pixel of max value. For example, if this value was 100 and pixels ranged from 0 to 255, then a pixel of value 0 would generate a value of 0, a pixel of value 102 would generate a value of 40, and a pixel of value 255 would generate a value of 100.")]
			public float MaxOutputValue = 1f;

			[TextureFileReference]
			[InspectorProperty(null, false, Label = "Texture", Order = 0, Tooltip = "The texture from which to read the data.")]
			public string Path;

			[InspectorProperty(null, false, Label = "Position", Order = 2, Tooltip = "The position of the center of the texture on the cube face. Coordinates are unit cube space, from -0.5 to 0.5.")]
			public Vector2d Position;

			[InspectorProperty(null, false, Label = "Rotation", Order = 3, Tooltip = "The rotation of the texture in degrees. NOTE: Only increments of 90 degrees will work.")]
			public float Rotation;

			[InspectorProperty(null, false, Label = "Size", Order = 4, Tooltip = "The size of the texture relative to the cube face. Coordinates are unit cube space with a size value of 1 filling the entire cubemap face.")]
			public Vector2d Size = new Vector2d(0.5, 0.5);

			[NonSerialized]
			public Texture2D Texture;

			[InspectorProperty(null, false, Label = "Texture Channel", Order = 7, Tooltip = "The texture channel from which values should be used for this texture.")]
			public TextureDataChannel TextureChannel;

			[InspectorProperty(null, false, Label = "Bits Per Pixel", Order = 8, Tooltip = "The number of bits per pixel used at runtime to represent the texture data. A value of 32 could be slightly more efficient on the CPU, but it can take way more memory at runtime, especially for large textures. It is recommended that this value be left at 8 bits per pixel.")]
			public TextureDataBitsPerPixel TextureChannelBitsPerPixel = TextureDataBitsPerPixel._8;

			public ISingleChannelTextureDataSampler Sampler { get; set; }

			public TextureDataItem()
			{
			}

			public TextureDataItem(XElement xml)
			{
				RestoreXml(xml);
			}

			public XElement CreateXml()
			{
				return new XElement("Texture", string.IsNullOrWhiteSpace(Path) ? null : new XAttribute("path", Path), new XAttribute("textureChannel", (int)TextureChannel), (TextureChannelBitsPerPixel == TextureDataBitsPerPixel._8) ? null : new XAttribute("textureChannelBitsPerPixel", (int)TextureChannelBitsPerPixel), new XAttribute("face", Face), new XAttribute("position", Position.XAttributeValue()), new XAttribute("rotation", Rotation), new XAttribute("size", Size.XAttributeValue()), new XAttribute("interpolationMethod", InterpolationMethod), new XAttribute("maxOutputValue", MaxOutputValue));
			}

			public void LoadTexture(PlanetTerrainDataScript terrainData)
			{
				if (Texture != null)
				{
					return;
				}
				try
				{
					Texture = null;
					if (!string.IsNullOrWhiteSpace(Path))
					{
						CelestialFile supportFile = terrainData.PlanetData.FileData.GetSupportFile(Path);
						Texture = supportFile.LoadTexture(mipmaps: false, linear: true, markNonReadable: false);
					}
				}
				catch (Exception exception)
				{
					Texture = null;
					Debug.LogException(exception);
				}
			}

			public void RestoreXml(XElement xml)
			{
				Path = (string)xml.Attribute("path");
				TextureChannel = (TextureDataChannel)((int?)xml.Attribute("textureChannel")).GetValueOrDefault();
				TextureChannelBitsPerPixel = (TextureDataBitsPerPixel)(((int?)xml.Attribute("textureChannelBitsPerPixel")) ?? 8);
				Face = xml.GetEnumAttribute("face", CubeFace.Xpos);
				Position = xml.GetVector2dAttribute("position");
				Rotation = ((float?)xml.Attribute("rotation")).GetValueOrDefault();
				Size = xml.GetVector2dAttribute("size");
				InterpolationMethod = xml.GetEnumAttribute("interpolationMethod", TextureDataSampleMode.Bilinear);
				MaxOutputValue = (float)xml.Attribute("maxOutputValue");
			}

			public void UnloadTexture()
			{
				if (Texture != null)
				{
					UnityEngine.Object.Destroy(Texture);
					Texture = null;
				}
			}
		}

		private Dictionary<CubeFace, List<CubeFaceTexture>> _cubeFaceTextures;

		[SerializeField]
