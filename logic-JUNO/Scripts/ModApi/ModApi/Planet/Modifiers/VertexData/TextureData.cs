		[DataSlot(DataSlotType.Output, "Output", false, true)]
		private int _dataIndexOutput;

		[SerializeField]
		private TextureDataItem[] _textures;

		private Dictionary<string, ISingleChannelTextureDataSampler> _textureSamplers;

		public override VertexDataType VertexDataType => VertexDataType.Both;

		public override void GetVertexData(PlanetVertexDataInput input, PlanetVertexData data)
		{
			double num = 0.0;
			GetCubeFaceAndPosition(input.Position, out var face, out var facePosition);
			if (_cubeFaceTextures.TryGetValue(face, out var value))
			{
				float[][] mapSampleArray = data.CacheData.MapSampleArray;
				for (int i = 0; i < value.Count; i++)
				{
					num += (double)value[i].Sample(facePosition, mapSampleArray);
				}
			}
			data.Data[_dataIndexOutput] = num;
		}

		public override void GetVertexData(PlanetVertexDataInput input, PlanetBiomeVertexData data)
		{
			double num = 0.0;
			GetCubeFaceAndPosition(input.Position, out var face, out var facePosition);
			if (_cubeFaceTextures.TryGetValue(face, out var value))
			{
				float[][] mapSampleArray = data.CommonData.CacheData.MapSampleArray;
				for (int i = 0; i < value.Count; i++)
				{
					num += (double)value[i].Sample(facePosition, mapSampleArray);
				}
			}
			data.Data[_dataIndexOutput] = num;
		}

		public override void Initialize(IPlanetData planetData)
		{
			base.Initialize(planetData);
			InitializeTextureSamplers();
			_cubeFaceTextures = new Dictionary<CubeFace, List<CubeFaceTexture>>(6, default(CubeFaceComparer));
			_cubeFaceTextures.Add(CubeFace.Xneg, new List<CubeFaceTexture>());
			_cubeFaceTextures.Add(CubeFace.Xpos, new List<CubeFaceTexture>());
			_cubeFaceTextures.Add(CubeFace.Yneg, new List<CubeFaceTexture>());
			_cubeFaceTextures.Add(CubeFace.Ypos, new List<CubeFaceTexture>());
			_cubeFaceTextures.Add(CubeFace.Zneg, new List<CubeFaceTexture>());
			_cubeFaceTextures.Add(CubeFace.Zpos, new List<CubeFaceTexture>());
			TextureDataItem[] textures = _textures;
			foreach (TextureDataItem textureDataItem in textures)
			{
				if (textureDataItem.Sampler != null)
				{
					CubeFaceTexture cubeFaceTexture = new CubeFaceTexture
					{
						Face = textureDataItem.Face,
						Size = textureDataItem.Size,
						InterpolationMethod = textureDataItem.InterpolationMethod,
						MaxOutputValue = textureDataItem.MaxOutputValue,
						Sampler = textureDataItem.Sampler
					};
					Vector2d vector2d = textureDataItem.Position - textureDataItem.Size * 0.5;
					Vector2d vector2d2 = vector2d + textureDataItem.Size;
					cubeFaceTexture.Bounds = new Vector4d(vector2d.x, vector2d.y, vector2d2.x, vector2d2.y);
					float num = Mathf.Abs(Mathf.Round(textureDataItem.Rotation / 90f));
					if (!Mathf.Approximately(textureDataItem.Rotation / 90f % 1f, 0f))
					{
						Debug.LogWarningFormat("TextureData currently only supports rotations in 90 degree increments. Rotation '{0}' degrees will be rounded to '{1}' degrees", textureDataItem.Rotation, num * 90f * Mathf.Sign(textureDataItem.Rotation));
					}
					CubeFaceTextureRotation rotation = CubeFaceTextureRotation.RotateDefault;
					bool flag = Mathf.Sign(textureDataItem.Rotation) >= 0f;
					for (int j = 0; (float)j < num; j++)
					{
						rotation = (flag ? RotationRight(rotation) : RotationLeft(rotation));
					}
					cubeFaceTexture.Rotation = rotation;
					_cubeFaceTextures[textureDataItem.Face].Add(cubeFaceTexture);
					WrapLeft(cubeFaceTexture);
					WrapRight(cubeFaceTexture);
					WrapUp(cubeFaceTexture);
					WrapDown(cubeFaceTexture);
				}
			}
		}

		public override void OnCreatingInPlanetStudio(PlanetTerrainDataScript terrainData, VertexDataPlanetModifier parentModifier)
		{
			base.OnCreatingInPlanetStudio(terrainData, parentModifier);
			_textures = new TextureDataItem[1]
			{
				new TextureDataItem()
			};
		}

		public override void SaveXml(XElement xml)
		{
			base.SaveXml(xml);
			xml.SetAttributeValue("dataIndexOutput", _dataIndexOutput);
			XElement xElement = new XElement("Textures");
			if (_textures != null)
			{
				TextureDataItem[] textures = _textures;
				foreach (TextureDataItem textureDataItem in textures)
				{
					xElement.Add(textureDataItem.CreateXml());
				}
			}
			xml.Add(xElement);
		}

		protected override void RestoreXml(XElement xml)
		{
			base.RestoreXml(xml);
			_dataIndexOutput = (int)xml.Attribute("dataIndexOutput");
			_textures = (from x in xml.Elements("Textures").Elements("Texture")
				select new TextureDataItem(x)).ToArray();
		}

		private ISingleChannelTextureDataSampler CreateSamplerFromTexture(TextureDataItem textureDataItem)
		{
			ISingleChannelTextureDataSampler result = null;
			bool num = textureDataItem.Texture != null;
			if (!num)
			{
				textureDataItem.LoadTexture(base.TerrainData);
			}
			if (textureDataItem.Texture != null)
			{
				ISingleChannelTextureDataSampler singleChannelTextureDataSampler2;
				if (textureDataItem.TextureChannelBitsPerPixel > TextureDataBitsPerPixel._8)
				{
					ISingleChannelTextureDataSampler singleChannelTextureDataSampler = new SingleChannelFloatTextureDataSampler(textureDataItem.Texture, (int)textureDataItem.TextureChannel);
					singleChannelTextureDataSampler2 = singleChannelTextureDataSampler;
				}
				else
				{
					ISingleChannelTextureDataSampler singleChannelTextureDataSampler = new SingleChannelByteTextureDataSampler(textureDataItem.Texture, (int)textureDataItem.TextureChannel);
					singleChannelTextureDataSampler2 = singleChannelTextureDataSampler;
				}
				result = singleChannelTextureDataSampler2;
			}
			if (!num)
			{
				textureDataItem.UnloadTexture();
			}
			return result;
		}

		private void GetCubeFaceAndPosition(Vector3d position, out CubeFace face, out Vector2d facePosition)
		{
			double num = ((position.x >= 0.0) ? position.x : (0.0 - position.x));
			double num2 = ((position.y >= 0.0) ? position.y : (0.0 - position.y));
			double num3 = ((position.z >= 0.0) ? position.z : (0.0 - position.z));
			if (num > num2)
			{
				if (num > num3)
				{
					if (position.x > 0.0)
					{
						face = CubeFace.Xpos;
						facePosition = new Vector2d(position.z / num, position.y / num) * 0.5;
					}
					else
					{
						face = CubeFace.Xneg;
						facePosition = new Vector2d((0.0 - position.z) / num, position.y / num) * 0.5;
					}
				}
				else if (position.z > 0.0)
				{
					face = CubeFace.Zpos;
					facePosition = new Vector2d((0.0 - position.x) / num3, position.y / num3) * 0.5;
				}
				else
				{
					face = CubeFace.Zneg;
					facePosition = new Vector2d(position.x / num3, position.y / num3) * 0.5;
				}
			}
			else if (num2 > num3)
			{
				if (position.y > 0.0)
				{
					face = CubeFace.Ypos;
					facePosition = new Vector2d(position.x / num2, position.z / num2) * 0.5;
				}
				else
				{
					face = CubeFace.Yneg;
					facePosition = new Vector2d(position.x / num2, (0.0 - position.z) / num2) * 0.5;
				}
			}
			else if (position.z > 0.0)
			{
				face = CubeFace.Zpos;
				facePosition = new Vector2d((0.0 - position.x) / num3, position.y / num3) * 0.5;
			}
			else
			{
				face = CubeFace.Zneg;
				facePosition = new Vector2d(position.x / num3, position.y / num3) * 0.5;
			}
		}

		private ISingleChannelTextureDataSampler InitializeTextureSampler(TextureDataItem textureDataItem)
		{
			if (string.IsNullOrEmpty(textureDataItem.Path))
			{
				return null;
			}
			CelestialFile supportFile = base.TerrainData.PlanetData.FileData.GetSupportFile(textureDataItem.Path);
			string fileName = $"TextureData_{supportFile.Id}_{textureDataItem.TextureChannel}{textureDataItem.TextureChannelBitsPerPixel}";
			string filePath = base.TerrainData.PlanetData.GeneratedData.GetFilePath(fileName, createDirectory: true);
			ISingleChannelTextureDataSampler singleChannelTextureDataSampler = null;
			if (!File.Exists(filePath))
			{
				singleChannelTextureDataSampler = CreateSamplerFromTexture(textureDataItem);
				using FileStream output = new FileStream(filePath, FileMode.Create);
				using BinaryWriter writer = new BinaryWriter(output);
				singleChannelTextureDataSampler.Save(writer);
			}
			else
			{
				using FileStream input = new FileStream(filePath, FileMode.Open);
				using BinaryReader reader = new BinaryReader(input);
				ISingleChannelTextureDataSampler singleChannelTextureDataSampler3;
				if (textureDataItem.TextureChannelBitsPerPixel > TextureDataBitsPerPixel._8)
				{
					ISingleChannelTextureDataSampler singleChannelTextureDataSampler2 = SingleChannelFloatTextureDataSampler.Load(reader);
					singleChannelTextureDataSampler3 = singleChannelTextureDataSampler2;
				}
				else
				{
					ISingleChannelTextureDataSampler singleChannelTextureDataSampler2 = SingleChannelByteTextureDataSampler.Load(reader);
					singleChannelTextureDataSampler3 = singleChannelTextureDataSampler2;
				}
				singleChannelTextureDataSampler = singleChannelTextureDataSampler3;
			}
			return singleChannelTextureDataSampler;
		}

		private void InitializeTextureSamplers()
		{
			_textureSamplers = new Dictionary<string, ISingleChannelTextureDataSampler>();
			TextureDataItem[] textures = _textures;
			foreach (TextureDataItem textureDataItem in textures)
			{
				ISingleChannelTextureDataSampler value = null;
				string key = textureDataItem.Path + "_" + textureDataItem.TextureChannel.ToString() + textureDataItem.TextureChannelBitsPerPixel;
				if (!_textureSamplers.TryGetValue(key, out value))
				{
					value = InitializeTextureSampler(textureDataItem);
					_textureSamplers.Add(key, value);
				}
				textureDataItem.Sampler = value;
			}
		}

		private CubeFaceTextureRotation RotationLeft(CubeFaceTextureRotation rotation)
		{
			return rotation switch
			{
				CubeFaceTextureRotation.RotateDefault => CubeFaceTextureRotation.Rotate270, 
				CubeFaceTextureRotation.Rotate90 => CubeFaceTextureRotation.RotateDefault, 
				CubeFaceTextureRotation.Rotate180 => CubeFaceTextureRotation.Rotate90, 
				CubeFaceTextureRotation.Rotate270 => CubeFaceTextureRotation.Rotate180, 
				_ => throw new InvalidOperationException(), 
			};
		}

		private CubeFaceTextureRotation RotationRight(CubeFaceTextureRotation rotation)
		{
			return rotation switch
			{
				CubeFaceTextureRotation.RotateDefault => CubeFaceTextureRotation.Rotate90, 
				CubeFaceTextureRotation.Rotate90 => CubeFaceTextureRotation.Rotate180, 
				CubeFaceTextureRotation.Rotate180 => CubeFaceTextureRotation.Rotate270, 
				CubeFaceTextureRotation.Rotate270 => CubeFaceTextureRotation.RotateDefault, 
				_ => throw new InvalidOperationException(), 
			};
		}

		private void WrapDown(CubeFaceTexture texture)
		{
			Vector4d bounds = texture.Bounds;
			if (bounds.y < -0.5)
			{
				CubeFaceTexture cubeFaceTexture = new CubeFaceTexture
				{
					Size = texture.Size,
					Rotation = texture.Rotation,
					InterpolationMethod = texture.InterpolationMethod,
					MaxOutputValue = texture.MaxOutputValue,
					Sampler = texture.Sampler
				};
				switch (texture.Face)
				{
				case CubeFace.Xneg:
					cubeFaceTexture.Face = CubeFace.Yneg;
					cubeFaceTexture.Size = new Vector2d(texture.Size.y, texture.Size.x);
					cubeFaceTexture.Bounds = new Vector4d(-1.0 - bounds.w, bounds.x, -1.0 - bounds.y, bounds.z);
					cubeFaceTexture.Rotation = RotationLeft(texture.Rotation);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapRight(cubeFaceTexture);
					break;
				case CubeFace.Xpos:
					cubeFaceTexture.Face = CubeFace.Yneg;
					cubeFaceTexture.Size = new Vector2d(texture.Size.y, texture.Size.x);
					cubeFaceTexture.Bounds = new Vector4d(bounds.y + 1.0, bounds.x, bounds.w + 1.0, bounds.z);
					cubeFaceTexture.Rotation = RotationRight(texture.Rotation);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapLeft(cubeFaceTexture);
					break;
				case CubeFace.Yneg:
					cubeFaceTexture.Face = CubeFace.Zpos;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x, -1.0 - bounds.w, bounds.z, -1.0 - bounds.y);
					cubeFaceTexture.Rotation = RotationRight(RotationRight(texture.Rotation));
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapUp(cubeFaceTexture);
					break;
				case CubeFace.Ypos:
					cubeFaceTexture.Face = CubeFace.Zneg;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x, bounds.y + 1.0, bounds.z, bounds.w + 1.0);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapDown(cubeFaceTexture);
					break;
				case CubeFace.Zneg:
					cubeFaceTexture.Face = CubeFace.Yneg;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x, bounds.y + 1.0, bounds.z, bounds.w + 1.0);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapDown(cubeFaceTexture);
					break;
				case CubeFace.Zpos:
					cubeFaceTexture.Face = CubeFace.Yneg;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x, -1.0 - bounds.w, bounds.z, -1.0 - bounds.y);
					cubeFaceTexture.Rotation = RotationRight(RotationRight(texture.Rotation));
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapUp(cubeFaceTexture);
					break;
				}
			}
		}

		private void WrapLeft(CubeFaceTexture texture)
		{
			Vector4d bounds = texture.Bounds;
			if (bounds.x < -0.5)
			{
				CubeFaceTexture cubeFaceTexture = new CubeFaceTexture
				{
					Size = texture.Size,
					Rotation = texture.Rotation,
					InterpolationMethod = texture.InterpolationMethod,
					MaxOutputValue = texture.MaxOutputValue,
					Sampler = texture.Sampler
				};
				switch (texture.Face)
				{
				case CubeFace.Xneg:
					cubeFaceTexture.Face = CubeFace.Zpos;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x + 1.0, bounds.y, bounds.z + 1.0, bounds.w);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapLeft(cubeFaceTexture);
					break;
				case CubeFace.Xpos:
					cubeFaceTexture.Face = CubeFace.Zneg;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x + 1.0, bounds.y, bounds.z + 1.0, bounds.w);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapLeft(cubeFaceTexture);
					break;
				case CubeFace.Yneg:
					cubeFaceTexture.Face = CubeFace.Xneg;
					cubeFaceTexture.Size = new Vector2d(texture.Size.y, texture.Size.x);
					cubeFaceTexture.Bounds = new Vector4d(bounds.y, -1.0 - bounds.z, bounds.w, -1.0 - bounds.x);
					cubeFaceTexture.Rotation = RotationRight(cubeFaceTexture.Rotation);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapUp(cubeFaceTexture);
					break;
				case CubeFace.Ypos:
					cubeFaceTexture.Face = CubeFace.Xneg;
					cubeFaceTexture.Size = new Vector2d(texture.Size.y, texture.Size.x);
					cubeFaceTexture.Bounds = new Vector4d(0.0 - bounds.w, 1.0 + bounds.x, 0.0 - bounds.y, 1.0 + bounds.z);
					cubeFaceTexture.Rotation = RotationLeft(cubeFaceTexture.Rotation);
					_cubeFaceTextures[cubeFaceTexture.Face].Add(cubeFaceTexture);
					WrapDown(cubeFaceTexture);
					break;
				case CubeFace.Zneg:
					cubeFaceTexture.Face = CubeFace.Xneg;
					cubeFaceTexture.Bounds = new Vector4d(bounds.x + 1.0, bounds.y, bounds.z + 1.0, bounds.w);
