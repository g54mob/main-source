			int num5 = FastFloor(num2);
			int num6 = FastFloor(num3);
			int x2 = num4 + 1;
			int y2 = num5 + 1;
			int z2 = num6 + 1;
			double t;
			double t2;
			double t3;
			switch (m_interp)
			{
			default:
				t = num - (double)num4;
				t2 = num2 - (double)num5;
				t3 = num3 - (double)num6;
				break;
			case Interpolation.Hermite:
				t = InterpHermiteFunc(num - (double)num4);
				t2 = InterpHermiteFunc(num2 - (double)num5);
				t3 = InterpHermiteFunc(num3 - (double)num6);
				break;
			case Interpolation.Quintic:
				t = InterpQuinticFunc(num - (double)num4);
				t2 = InterpQuinticFunc(num2 - (double)num5);
				t3 = InterpQuinticFunc(num3 - (double)num6);
				break;
			}
			int num7 = Hash3D(seed, num4, num5, num6) & 0xFF;
			int num8 = Hash3D(seed, x2, num5, num6) & 0xFF;
			double a = Lerp(CELL_3D_X[num7], CELL_3D_X[num8], t);
			double a2 = Lerp(CELL_3D_Y[num7], CELL_3D_Y[num8], t);
			double a3 = Lerp(CELL_3D_Z[num7], CELL_3D_Z[num8], t);
			num7 = Hash3D(seed, num4, y2, num6) & 0xFF;
			num8 = Hash3D(seed, x2, y2, num6) & 0xFF;
			double b = Lerp(CELL_3D_X[num7], CELL_3D_X[num8], t);
			double b2 = Lerp(CELL_3D_Y[num7], CELL_3D_Y[num8], t);
			double b3 = Lerp(CELL_3D_Z[num7], CELL_3D_Z[num8], t);
			double a4 = Lerp(a, b, t2);
			double a5 = Lerp(a2, b2, t2);
			double a6 = Lerp(a3, b3, t2);
			num7 = Hash3D(seed, num4, num5, z2) & 0xFF;
			num8 = Hash3D(seed, x2, num5, z2) & 0xFF;
			a = Lerp(CELL_3D_X[num7], CELL_3D_X[num8], t);
			a2 = Lerp(CELL_3D_Y[num7], CELL_3D_Y[num8], t);
			a3 = Lerp(CELL_3D_Z[num7], CELL_3D_Z[num8], t);
			num7 = Hash3D(seed, num4, y2, z2) & 0xFF;
			num8 = Hash3D(seed, x2, y2, z2) & 0xFF;
			b = Lerp(CELL_3D_X[num7], CELL_3D_X[num8], t);
			b2 = Lerp(CELL_3D_Y[num7], CELL_3D_Y[num8], t);
			b3 = Lerp(CELL_3D_Z[num7], CELL_3D_Z[num8], t);
			x += Lerp(a4, Lerp(a, b, t2), t3) * perturbAmp;
			y += Lerp(a5, Lerp(a2, b2, t2), t3) * perturbAmp;
			z += Lerp(a6, Lerp(a3, b3, t2), t3) * perturbAmp;
		}

