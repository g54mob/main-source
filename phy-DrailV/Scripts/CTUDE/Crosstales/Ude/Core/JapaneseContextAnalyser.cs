		private int[] relSample = new int[6];

		private int totalRel;

		private int lastCharOrder;

		private int needToSkipCharNum;

		private bool done;

		public JapaneseContextAnalyser()
		{
			Reset();
		}

		public float GetConfidence()
		{
			if (totalRel > 4)
			{
				return (float)(totalRel - relSample[0]) / (float)totalRel;
			}
			return -1f;
		}

		public void HandleData(byte[] buf, int offset, int len)
		{
			int charLen = 0;
			int num = offset + len;
			if (done)
			{
				return;
			}
			int num2 = needToSkipCharNum + offset;
			while (num2 < num)
			{
				int order = GetOrder(buf, num2, out charLen);
				num2 += charLen;
				if (num2 > num)
				{
					needToSkipCharNum = num2 - num;
					lastCharOrder = -1;
					continue;
				}
				if (order != -1 && lastCharOrder != -1)
				{
					totalRel++;
					if (totalRel > 1000)
					{
						done = true;
						break;
					}
					relSample[jp2CharContext[lastCharOrder, order]]++;
				}
				lastCharOrder = order;
			}
		}

		public void HandleOneChar(byte[] buf, int offset, int charLen)
		{
			if (totalRel > 1000)
			{
				done = true;
			}
			if (!done)
			{
				int num = ((charLen == 2) ? GetOrder(buf, offset) : (-1));
				if (num != -1 && lastCharOrder != -1)
				{
					totalRel++;
					relSample[jp2CharContext[lastCharOrder, num]]++;
				}
				lastCharOrder = num;
			}
		}

		public void Reset()
		{
			totalRel = 0;
			for (int i = 0; i < 6; i++)
			{
				relSample[i] = 0;
				needToSkipCharNum = 0;
				lastCharOrder = -1;
				done = false;
			}
		}

		protected abstract int GetOrder(byte[] buf, int offset, out int charLen);

		protected abstract int GetOrder(byte[] buf, int offset);

		public bool GotEnoughData()
		{
			return totalRel > 100;
		}
